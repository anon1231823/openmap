# each instance's bosses, in the game's order (DungeonEncounter)
def boss_lists(rows):
    lists = {}
    for r in sorted(rows, key=lambda r: (int(r["MapID"]), int(r["OrderIndex"]))):
        m = int(r["MapID"])
        if m > 0 and r["Name_lang"] not in lists.setdefault(m, []): lists[m].append(r["Name_lang"])
    return lists

