def item(i):
    lv = lambda v: "nil" if v is None else str(v)
    return "{ %d, %s, %s, %s, %s }" % (i["id"], lua_str(i["name"]), "true" if i["raid"] else "false", lv(i["min"]), lv(i["max"]))

