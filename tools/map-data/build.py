def levels(name, raid):
    lv = LEVELS.get(name) or LEVELS.get(WING_OF.get(name))   # (a wing the finder doesn't list: its dungeon's)
    if not lv: return None, None
    return lv, lv if raid else min(lv + SPAN, 60)

